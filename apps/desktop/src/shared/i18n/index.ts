/**
 * i18n tối giản zero-dep — VI mặc định, EN phụ.
 * t() đọc locale ref nên template tự re-render khi đổi ngôn ngữ.
 */
import { ref } from 'vue'

export type Locale = 'vi' | 'en'

export const locale = ref<Locale>('vi')

const LOCALE_KEY = 'antares.locale'

export function setLocale(l: Locale): void {
  locale.value = l
  try {
    localStorage.setItem(LOCALE_KEY, l)
  } catch {
    /* private mode */
  }
}

export function initLocale(): void {
  try {
    const saved = localStorage.getItem(LOCALE_KEY)
    if (saved === 'en' || saved === 'vi') locale.value = saved
  } catch {
    /* private mode */
  }
}

