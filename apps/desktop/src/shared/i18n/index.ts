/**
 * Translate — fallback về key nếu thiếu (dễ debug khi thêm mới).
 * Hỗ trợ tham số: t('play.blockers', { n: 2 }) → "{n} blocker(s)..."
 */
export function t(key: string, params?: Record<string, string | number>): string {
  let msg = messages[locale.value][key] ?? messages.vi[key] ?? key
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      msg = msg.split(`{${k}}`).join(String(v))
    }
  }
  return msg
}
